@app.post("/generate", response_class=HTMLResponse)
async def generate_story_endpoint(
    file: UploadFile = File(...),
    user_name: str = Form(...),
    user_pronouns: str = Form(...),
    other_name: str = Form(...),
    other_pronouns: str = Form(...)
):
    if not file.filename.endswith('.txt'):
        raise HTTPException(status_code=400, detail="Only exported .txt chat files are accepted.")

    raw_bytes = await file.read()
    decoded_text = raw_bytes.decode('utf-8', errors='ignore')

    structured_data = parse_whatsapp_transcript(decoded_text)
    if not structured_data:
        return """
        <div style="font-family:sans-serif; text-align:center; padding:50px;">
            <h2>Could not parse any messages from this file.</h2>
            <p>Ensure you are uploading an unedited exported WhatsApp .txt file.</p>
            <a href="/">← Try Again</a>
        </div>
        """

    chat_transcript = "\n".join(
        f"[{m['date']}] {m['sender']}: {m['message']}" for m in structured_data
    )

    stats = compute_transcript_stats(structured_data)

    try:
        profile = analyze_relationship(client, chat_transcript, stats)
    except Exception as e:
        return f"<div style='padding:40px; font-family:sans-serif;'><h3>Intelligence Analysis Error:</h3><p>{str(e)}</p><a href='/'>Go back</a></div>"

    conn_description = profile.get('connection_description', 'A digital correspondence.')
    observed_activity = profile.get('observed_activity', 'Activity documented across transcript span.')
    verbatim_quotes = ", ".join(f'"{q}"' for q in profile.get('key_verbatim_quotes', []))
    specific_topics = ", ".join(profile.get('specific_topics_and_events', ['General exchanges']))
    turning_points = ", ".join(profile.get('turning_points', ['None noted']))
    communication_changes = ", ".join(profile.get('communication_changes', ['None noted']))

    system_prompt = f"""
    You are an expert biographer writing a detailed, chronological memoir chapter based strictly on a WhatsApp chat transcript.

    PARTICIPANTS:
    - Participant 1: {user_name} (Pronouns: {user_pronouns})
    - Participant 2: {other_name} (Pronouns: {other_pronouns})

    STATISTICS:
    - Total Messages: {stats['total_messages']}
    - Date Range: {stats['first_message_date']} to {stats['last_message_date']} ({stats['span_days']} days total)
    - Longest Gap: {stats['longest_communication_gap_days']} days

    METADATA ANALYSIS:
    - Connection Style: {conn_description}
    - Observed Timeline: {observed_activity}
    - Key Verbatim Quotes: {verbatim_quotes}
    - Major Topics Discussed: {specific_topics}
    - Key Moments & Shifts: {turning_points}
    - Response Pacing: {communication_changes}

    WRITING RULES:
    1. SIMPLE TITLE: Start with a simple, concise Markdown header `# Title` based directly on the main theme or overall subject of the chat.
    2. SUBSTANTIAL & DETAILED STORY: Write a full, long-form narrative consisting of 4 to 6 substantial paragraphs. Thoroughly detail what occurred, what was discussed, decisions made, and how events unfolded over time.
    3. STRICT CHRONOLOGICAL FLOW: Follow the story step-by-step in the order events happened, moving sequentially from the earliest messages in the transcript, through the middle discussions, to the final exchanges.
    4. NO EMOJIS: Do NOT include any emojis anywhere in the title or narrative text. Zero emojis.
    5. COMPLETE COVERAGE: Read through ALL sections of the transcript provided so no major part of the timeline is omitted.
    6. VERBATIM QUOTES: Integrate real verbatim quotes seamlessly into paragraphs with quotation marks to ground the story in factual evidence.
    7. ZERO FABRICATION & NO AI CLICHÉS: Only recount facts present in the text. Avoid generic AI cliché words.
    """

    models = get_valid_text_models(client)
    story_md = None

    for model in models:
        fraction = 1.0  # Start by trying 100% of the entire chat
        
        while fraction > 0.1:
            transcript_sample = get_max_allowed_transcript(chat_transcript, fraction)
            print(f"[Narrative Engine] Attempting to process {(fraction*100):.0f}% of chat with {model}...")
            
            try:
                response = client.chat.completions.create(
                    model=model,
                    messages=[
                        {"role": "system", "content": system_prompt},
                        {"role": "user", "content": f"Full Timeline Transcript:\n\n{transcript_sample}"}
                    ],
                    temperature=0.35,
                    max_tokens=2500
                )
                story_md = response.choices[0].message.content
                print(f"[Success] Generated narrative using {(fraction*100):.0f}% of the chat log!")
                break # Success! Break out of the while loop
                
            except Exception as e:
                error_msg = str(e).lower()
                # If the API says the file is too big, shrink it by 20% and try again immediately
                if "too large" in error_msg or "rate limit" in error_msg or "tokens" in error_msg or "rate_limit_exceeded" in error_msg:
                    print(f"[-] Groq rejected file size. Scaling down...")
                    fraction -= 0.20
                else:
                    print(f"[-] Model {model} failed for another reason: {e}")
                    break # Break while loop, try the next model in the list
                    
        if story_md:
            break # Success! Break out of the model loop

    if not story_md:
        return "<div style='padding:40px; font-family:sans-serif;'><h3>Narrative Generation Error:</h3><p>All accessible models failed to generate narrative, or the file size could not be scaled down enough to fit the API limits.</p><a href='/'>Go back</a></div>"

    rendered_html = markdown_to_html(story_md)

