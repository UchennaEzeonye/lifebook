def get_max_allowed_transcript(chat_transcript: str, fraction: float) -> str:
    """
    Dynamically sizes the transcript. If fraction is 1.0, it returns 100% of the chat.
    If less than 1.0, it perfectly balances the start, middle, and end to fit the API limit.
    """
    if fraction >= 1.0:
        return chat_transcript

    target_length = int(len(chat_transcript) * fraction)
    segment_size = target_length // 3
    
    beginning = chat_transcript[:segment_size]
    mid_start = (len(chat_transcript) // 2) - (segment_size // 2)
    middle = chat_transcript[mid_start : mid_start + segment_size]
    end = chat_transcript[-segment_size:]

    return (
        f"--- EARLY CHAT PERIOD ---\n{beginning}\n\n"
        f"--- MIDDLE CHAT PERIOD ---\n{middle}\n\n"
        f"--- RECENT CHAT PERIOD ---\n{end}"
    )


def markdown_to_html(md_text: str) -> str:
    """Converts markdown generated by LLM into clean HTML."""
    html_lines = []
    in_paragraph = False

    for line in md_text.splitlines():
        line_str = line.strip()

        if not line_str:
            if in_paragraph:
                html_lines.append("</p>")
                in_paragraph = False
            continue

        if line_str.startswith("# "):
            if in_paragraph: html_lines.append("</p>"); in_paragraph = False
            html_lines.append(f"<h1>{line_str[2:]}</h1>")
            continue
        elif line_str.startswith("## "):
            if in_paragraph: html_lines.append("</p>"); in_paragraph = False
            html_lines.append(f"<h2>{line_str[3:]}</h2>")
            continue
        elif line_str.startswith("### "):
            if in_paragraph: html_lines.append("</p>"); in_paragraph = False
            html_lines.append(f"<h3>{line_str[4:]}</h3>")
            continue

        line_str = re.sub(r'\*\*(.*?)\*\*', r'<strong>\1</strong>', line_str)
        line_str = re.sub(r'\*(.*?)\*', r'<em>\1</em>', line_str)

        if not in_paragraph:
            html_lines.append("<p>")
            in_paragraph = True
            html_lines.append(line_str)
        else:
            html_lines.append(f" {line_str}")

    if in_paragraph:
        html_lines.append("</p>")

    return "\n".join(html_lines)


